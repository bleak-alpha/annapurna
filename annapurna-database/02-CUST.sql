CREATE TABLE CUST_PERSON_ACC_TBL (
    customer_id      NUMBER(10)     DEFAULT CUST_PERSON_ACC_SEQ.NEXTVAL PRIMARY KEY,
    customer_number  VARCHAR2(50)   NOT NULL,
    name             VARCHAR2(255)  NOT NULL,
    phone            VARCHAR2(20),
