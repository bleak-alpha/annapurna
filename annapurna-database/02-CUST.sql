-- Prevent manual customer_id insertion (sequence-only)
CREATE OR REPLACE TRIGGER CUST_PREVENT_MANUAL_CUST_ID_TRG
    BEFORE INSERT ON CUST_PERSON_ACC_TBL
    FOR EACH ROW
DECLARE
    v_currval NUMBER;
BEGIN
    IF :NEW.customer_id IS NOT NULL THEN
        BEGIN
            v_currval := CUST_PERSON_ACC_SEQ.CURRVAL;
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE = -8002 THEN   -- CURRVAL not yet defined in this session
                    RETURN;
                END IF;
                RAISE;
        END;

        IF :NEW.customer_id != v_currval THEN
            RAISE_APPLICATION_ERROR(-20201,
                'Cannot manually set customer_id. It must be generated by CUST_PERSON_ACC_SEQ.');
        END IF;
    END IF;
END;
/

-- Maintain audit columns and optimistic-lock version on update
CREATE OR REPLACE TRIGGER CUST_PERSON_ACC_AUDIT_TRG
    BEFORE UPDATE ON CUST_PERSON_ACC_TBL
    FOR EACH ROW
BEGIN
    :NEW.updated_date := SYSTIMESTAMP;
    :NEW.version_no   := NVL(:OLD.version_no, 0) + 1;
END;
/


--------------------------------------------------------------------------------
-- 5: views
-- DEPENDS ON- 2: tables
--------------------------------------------------------------------------------

CREATE OR REPLACE VIEW CUST_CUSTOMER_DUES_V AS
SELECT customer_id, customer_number, name, phone, total_due
  FROM CUST_PERSON_ACC_TBL
 WHERE is_active = 1
   AND total_due > 0
 ORDER BY total_due DESC;

CREATE OR REPLACE VIEW CUST_ACTIVE_CUSTOMERS_V AS
SELECT customer_id, customer_number, name, phone, email, loyalty_points
  FROM CUST_PERSON_ACC_TBL
 WHERE is_active = 1
 ORDER BY name;


